const run = (text, opts = {}) => new TextRun({ text, font: 'Sylfaen', size: 19, ...opts });

function headerCell(text, w, align = AlignmentType.LEFT) {
  return new TableCell({
    width: { size: w, type: WidthType.DXA }, borders,
    shading: { fill: C_BLUE, type: ShadingType.CLEAR },
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    verticalAlign: VerticalAlign.CENTER,
    children: [new Paragraph({ alignment: align, children: [run(text, { bold: true, color: C_WHITE, size: 18 })] })],
  });
}
function cell(children, w, opts = {}) {
  return new TableCell({
    width: { size: w, type: WidthType.DXA }, borders,
    shading: opts.fill ? { fill: opts.fill, type: ShadingType.CLEAR } : undefined,
    margins: { top: 50, bottom: 50, left: 90, right: 90 },
    verticalAlign: VerticalAlign.CENTER,
    children: Array.isArray(children) ? children : [new Paragraph({ alignment: opts.align || AlignmentType.LEFT, children: [children] })],
  });
}

